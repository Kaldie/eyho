package main

import (
	"context"
	"fmt"
	"log"
	"net/http"
	"os"

	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/joho/godotenv"

	"github.com/eyho/eyho/src/api"
	"github.com/eyho/eyho/src/services"
)

func main() {
	// Load environment variables from .env (if present). In production, env
	// vars are set by the platform and .env is absent — godotenv silently
	// continues if the file does not exist.
	if err := godotenv.Load(); err != nil {
		log.Println("no .env file found, relying on environment variables")
	}

	dbURL := mustEnv("DATABASE_URL")
	stripeKey := mustEnv("STRIPE_SECRET_KEY")
	services.InitStripe(stripeKey)

	// Initialise the pgx connection pool. A nil pool is acceptable here if
	// we are running without a database (e.g., during early scaffold testing),
	// but we log a warning so the gap is visible.
	pool, err := pgxpool.New(context.Background(), dbURL)
	if err != nil {
		log.Fatalf("failed to create database pool: %v", err)
	}
	defer pool.Close()

	if err := pool.Ping(context.Background()); err != nil {
		log.Fatalf("database ping failed: %v", err)
	}

	// Wire stub services. Replace with real implementations once db/ queries
	// are generated by sqlc.
	listingSvc := services.NewStubListingService()
	claimSvc := services.NewStubClaimService()

	// Suppress "pool declared but unused" lint until services use it.
	_ = pool

	r := api.NewRouter(listingSvc, claimSvc)

	port := getEnv("PORT", "8080")
	addr := fmt.Sprintf(":%s", port)
	log.Printf("eyho backend listening on %s", addr)

	if err := http.ListenAndServe(addr, r); err != nil {
		log.Fatalf("server error: %v", err)
	}
}

// mustEnv returns the value of the named environment variable or exits.
func mustEnv(key string) string {
	v := os.Getenv(key)
	if v == "" {
		log.Fatalf("required environment variable %q is not set", key)
	}
	return v
}

// getEnv returns the value of the named environment variable or a default.
func getEnv(key, defaultVal string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return defaultVal
}
